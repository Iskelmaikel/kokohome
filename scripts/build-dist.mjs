// Builds dist/ for HACS: `node scripts/build-dist.mjs`.
// HACS downloads every .js file in dist/ into one folder and registers
// dist/kokohome.js, so the cards go next to the entry with flat imports.
// No bundler needed; the files are copied as they are.
import { readFile, writeFile, readdir, rm, mkdir, copyFile } from 'node:fs/promises'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const DIST = join(ROOT, 'dist')
await rm(DIST, { recursive: true, force: true })
await mkdir(DIST)

for (const f of await readdir(join(ROOT, 'cards'))) {
  if (f.endsWith('.js')) await copyFile(join(ROOT, 'cards', f), join(DIST, f))
}
await copyFile(join(ROOT, 'kokonut-lamp.js'), join(DIST, 'kokonut-lamp.js'))

let entry = await readFile(join(ROOT, 'kokohome.js'), 'utf8')
entry = entry.replaceAll("'./cards/", "'./")
// The pull-cord lamp loads React from a CDN, so load it on the side: if that
// fails (offline), every other card still works.
entry += `
import('./kokonut-lamp.js').catch((e) => console.warn('Kokohome: the lamp card could not load', e))
`
await writeFile(join(DIST, 'kokohome.js'), `// Generated by scripts/build-dist.mjs — edit kokohome.js and cards/ instead.\n${entry}`)
console.log('dist/ built:', (await readdir(DIST)).length, 'files')
